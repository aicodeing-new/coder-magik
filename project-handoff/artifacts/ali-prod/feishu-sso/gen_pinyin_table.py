"""Generate pinyin_table.py from mozillazg/pinyin-data (first Mandarin reading).

Usage: python3 gen_pinyin_table.py pinyin.txt pinyin_table.py
Input lines look like: U+5F20: zhāng  # 张
The table keeps one toneless lowercase reading per character, restricted to the
CJK Unified Ideographs block (U+4E00..U+9FFF) plus U+3007, enough for names.
"""
import re
import sys
import unicodedata


def strip_tones(syllable):
    # NFD decomposition turns accented vowels into a base letter plus
    # combining marks. A combining diaeresis on "u" means ü, romanized "v".
    out = []
    for c in unicodedata.normalize("NFD", syllable):
        if unicodedata.combining(c):
            if ord(c) == 0x0308 and out and out[-1] == "u":
                out[-1] = "v"
        elif "a" <= c <= "z":
            out.append(c)
        else:
            return None
    return "".join(out) or None


def main(src, dst):
    entries = {}
    with open(src, encoding="utf-8") as f:
        for line in f:
            match = re.match(r"(U\+[0-9A-F]{4}): (\S+)", line)
            if not match:
                continue
            code = int(match.group(1)[2:], 16)
            if code != 0x3007 and not 0x4E00 <= code <= 0x9FFF:
                continue
            reading = strip_tones(match.group(2).split(",")[0])
            if reading:
                entries[chr(code)] = reading

    with open(dst, "w", encoding="utf-8") as f:
        f.write('"""Generated by gen_pinyin_table.py from mozillazg/pinyin-data.\n')
        f.write("One toneless lowercase reading per character (most common Mandarin\n")
        f.write("reading); covers the CJK Unified Ideographs block. Do not edit.\n")
        f.write('"""\n\nPINYIN = {\n')
        for char in sorted(entries):
            f.write("    '%s': '%s',\n" % (char, entries[char]))
        f.write("}\n")
    print("wrote %d entries to %s" % (len(entries), dst))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
